function drawReply(decks,target,reason){const id=target+':'+reason;const options=[replies[target][reason],...additionalReplies[target][reason]];const previous=decks[id]||{};let remaining=Array.isArray(previous.remaining)?previous.remaining.filter(n=>Number.isInteger(n)&&n>=0&&n<options.length):[];if(!remaining.length){remaining=shuffle(options.map((_,i)=>i));if(remaining.length>1&&remaining[0]===previous.last){const swap=remaining.findIndex(i=>i!==previous.last);[remaining[0],remaining[swap]]=[remaining[swap],remaining[0]]}}const picked=remaining.shift();return {text:options[picked],decks:{...decks,[id]:{remaining,last:picked}}}}
